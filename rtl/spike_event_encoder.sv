/*
------------------------------------------------------------------------------
Module: spike_event_encoder
Authors: MD & ChatGPT
Date: 17.07.2026

Description:
Converts a parallel spike vector generated by a neuron population
into a serialized event stream.

The neuron_array produces:
    spikes[NUM_NEURONS-1:0]
    
However, the synaptic subsystem processes spikes one neuron at a time.

This module scans the spike vector and generates:
    event_valid
    neuron_id

Example:

Input:
    spikes = 8'b00101000

Output sequence:
    cycle 1:
        event_valid = 1
        neuron_id   = 3

    cycle 2:
        event_valid = 1
        neuron_id   = 5

After all spikes have been emitted:
    done = 1

This module provides the interface between layers:
    neuron_array
        to
    spike_event_encoder
        to
    next snn_layer

------------------------------------------------------------------------------
*/

module spike_event_encoder #(
    // Number of neurons in the source layer
    parameter int unsigned NUM_NEURONS = 256,
    parameter int unsigned ID_WIDTH =
        (NUM_NEURONS <= 1) ? 1 : $clog2(NUM_NEURONS)
)(  // INPUTS
    //==========================================================================
    // Clock and reset
    //==========================================================================
    input logic clk,
    input logic rst,

    //==========================================================================
    // Spike vector input:
    // Generated directly by neuron_array.
    // Each bit represents one neuron spike.
    //==========================================================================
    input logic [NUM_NEURONS-1:0]
        spikes,

    //==========================================================================
    // Encoder control
    // start captures the spike vector and begins serialization.
    //==========================================================================
    input logic start,

    // Downstream backpressure. event_valid/neuron_id remain stable until ready.
    input logic event_ready,

    // OUTPUTS
    //==========================================================================
    // Event output:
    // One active event is produced per cycle.
    //==========================================================================
    output logic event_valid,
    output logic [ID_WIDTH-1:0]
        neuron_id,

    //==========================================================================
    // Completion indicator:
    // Asserted when all spike events have been emitted.
    //==========================================================================
    output logic done
);

    //----------------------------------------------------------------------
    // Local Parameters
    //----------------------------------------------------------------------

    localparam logic [ID_WIDTH-1:0] LAST_NEURON = ID_WIDTH'(NUM_NEURONS - 1);

    typedef enum logic {
        IDLE,
        ENCODE
    } state_t;

    //----------------------------------------------------------------------
    // Internal Signals
    //----------------------------------------------------------------------

    state_t state;
    logic [NUM_NEURONS-1:0] spike_reg;
    logic [ID_WIDTH-1:0] scan_idx;

    //----------------------------------------------------------------------
    // FSM
    //----------------------------------------------------------------------

    always_ff @(posedge clk or posedge rst) begin
        if (rst) begin
            state       <= IDLE;
            spike_reg   <= '0;
            scan_idx    <= '0;
            event_valid <= 1'b0;
            neuron_id   <= '0;
            done        <= 1'b0;
        end
        else begin
            // Default pulse output
            done        <= 1'b0;

            case (state)
                //----------------------------------------------------------
                // Wait for a new spike vector.
                //----------------------------------------------------------
                IDLE: begin
                    scan_idx <= '0;
                    event_valid <= 1'b0;
                    if (start) begin
                        spike_reg <= spikes;
                        state <= ENCODE;
                    end
                end

                //----------------------------------------------------------
                // Serialize spike events.
                //----------------------------------------------------------
                ENCODE: begin
                    if (!event_valid) begin
                        if (spike_reg[scan_idx]) begin
                            event_valid <= 1'b1;
                            neuron_id   <= scan_idx;
                        end
                        else if (scan_idx == LAST_NEURON) begin
                            done  <= 1'b1;
                            state <= IDLE;
                        end
                        else begin
                            scan_idx <= scan_idx + 1'b1;
                        end
                    end
                    else if (event_ready) begin
                        event_valid <= 1'b0;
                        if (scan_idx == LAST_NEURON) begin
                            done  <= 1'b1;
                            state <= IDLE;
                        end
                        else begin
                            scan_idx <= scan_idx + 1'b1;
                        end
                    end
                end
            endcase
        end
    end
endmodule
